-- Run once as ACCOUNTADMIN (or adapt to your organization's governance model).
-- DataMind never needs write access to source data.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS DATAMIND_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 30;

CREATE ROLE IF NOT EXISTS DATAMIND_READER;
GRANT USAGE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_READER;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DATAMIND_READER;

-- Replace YOUR_USERNAME before running.
-- GRANT ROLE DATAMIND_READER TO USER YOUR_USERNAME;

-- OPTIONAL: Live Data Mutation Demo Database & Staging Table
-- Used by `datamind demo-mutation` to prove that answers change when data changes.
CREATE DATABASE IF NOT EXISTS DATAMIND_DEMO;
GRANT ALL PRIVILEGES ON DATABASE DATAMIND_DEMO TO ROLE DATAMIND_READER;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE DATAMIND_DEMO TO ROLE DATAMIND_READER;

USE DATABASE DATAMIND_DEMO;
CREATE TABLE IF NOT EXISTS DATAMIND_DEMO.PUBLIC.DATAMIND_DEMO_ALERTS (
    ALERT_ID INT AUTOINCREMENT,
    SEVERITY VARCHAR(16) DEFAULT 'CRITICAL',
    MESSAGE VARCHAR(256),
    STATUS VARCHAR(16) DEFAULT 'PENDING',
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
GRANT ALL PRIVILEGES ON TABLE DATAMIND_DEMO.PUBLIC.DATAMIND_DEMO_ALERTS TO ROLE DATAMIND_READER;
